#!/usr/bin/env node
/**
 * Builds platform outputs from the framework-independent token JSON.
 *
 *   node design-system/scripts/build.mjs
 *
 * Outputs:
 *   design-system/dist/tokens.css    CSS custom properties (any web stack)
 *   design-system/dist/tokens.json   Resolved values, no metadata (any platform: RN, Flutter, native)
 *   design-system/dist/tokens.js     ESM object (JS/TS stacks, incl. React Native)
 *   design-system/dist/tokens.d.ts   Types for tokens.js
 *   website/src/styles/tokens.css    Tailwind v4 @theme mapping for the website
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => JSON.parse(readFileSync(join(root, "tokens", f), "utf8"));

const sources = ["colors", "typography", "spacing", "radii", "shadows", "motion"].map((f) => read(`${f}.json`));
const all = Object.assign({}, ...sources);

/** Strip $type/$description and unwrap $value. */
function resolve(node) {
  if (node && typeof node === "object" && !Array.isArray(node)) {
    if ("$value" in node) return node.$value;
    const out = {};
    for (const [k, v] of Object.entries(node)) if (!k.startsWith("$")) out[k] = resolve(v);
    return out;
  }
  return node;
}
const tokens = resolve(all);

const shadowCss = (s) => `${s.offsetX}px ${s.offsetY}px ${s.blur}px ${s.spread}px ${s.color}`;
const fontCss = (f) => f.map((n) => (n.includes(" ") ? `"${n}"` : n)).join(", ");

// ---------- Generic CSS custom properties ----------
const vars = [];
const walk = (obj, path) => {
  for (const [k, v] of Object.entries(obj)) {
    const p = [...path, k];
    if (v && typeof v === "object" && !Array.isArray(v) && !("offsetX" in v)) walk(v, p);
    else {
      let val = v;
      if (Array.isArray(v)) val = p[0] === "motion" ? `cubic-bezier(${v.join(", ")})` : fontCss(v);
      else if (v && typeof v === "object") val = shadowCss(v);
      else if (typeof v === "number" && ["space", "radius", "layout"].includes(p[0])) val = `${v}px`;
      else if (typeof v === "number" && p[0] === "motion" && p[1] === "duration") val = `${v}ms`;
      vars.push(`  --hc-${p.join("-")}: ${val};`);
    }
  }
};
const { type: typeScale, ...rest } = tokens;
walk(rest, []);
for (const [name, t] of Object.entries(typeScale)) {
  vars.push(`  --hc-type-${name}-size: ${t.size}px;`);
  if (t.sizeMobile) vars.push(`  --hc-type-${name}-size-mobile: ${t.sizeMobile}px;`);
  vars.push(`  --hc-type-${name}-line-height: ${t.lineHeight};`);
  vars.push(`  --hc-type-${name}-letter-spacing: ${t.letterSpacing}em;`);
  vars.push(`  --hc-type-${name}-weight: ${t.weight};`);
}

const header = "/* AUTO-GENERATED by design-system/scripts/build.mjs — edit design-system/tokens/*.json instead. */\n";
mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist/tokens.css"), `${header}:root {\n${vars.join("\n")}\n}\n`);
writeFileSync(join(root, "dist/tokens.json"), JSON.stringify(tokens, null, 2) + "\n");
writeFileSync(join(root, "dist/tokens.js"), `${header}export const tokens = ${JSON.stringify(tokens, null, 2)};\nexport default tokens;\n`);
const toType = (v, indent = "  ") => {
  if (Array.isArray(v)) return `readonly ${typeof v[0] === "number" ? "number" : "string"}[]`;
  if (v && typeof v === "object") {
    const inner = Object.entries(v).map(([k, x]) => `${indent}  ${JSON.stringify(k)}: ${toType(x, indent + "  ")};`);
    return `{\n${inner.join("\n")}\n${indent}}`;
  }
  return typeof v;
};
writeFileSync(join(root, "dist/tokens.d.ts"), `${header}export declare const tokens: ${toType(tokens, "")};\nexport default tokens;\n`);

// ---------- Tailwind v4 theme for the website ----------
const c = tokens.color;
const tw = [
  `  --color-ink: ${c.brand.ink};`,
  `  --color-ink-raised: ${c.brand["ink-raised"]};`,
  `  --color-citrus: ${c.brand.citrus};`,
  `  --color-citrus-hover: ${c.brand["citrus-hover"]};`,
  `  --color-accent-ink: ${c.brand["accent-ink"]};`,
  `  --color-olive: ${c.brand.olive};`,
  `  --color-stone: ${c.brand.stone};`,
  `  --color-porcelain: ${c.surface.porcelain};`,
  `  --color-card: ${c.surface.card};`,
  `  --color-muted: ${c.text.secondary};`,
  `  --color-line: ${c.border.default};`,
  `  --color-line-strong: ${c.border.strong};`,
  `  --color-success: ${c.feedback.success};`,
  `  --color-error: ${c.feedback.error};`,
  "",
  `  --font-sans: var(--font-manrope), ${fontCss(tokens.font.family.sans)};`,
  "",
  ...Object.entries(tokens.radius).map(([k, v]) => `  --radius-${k}: ${v === 999 ? "9999px" : `${v}px`};`),
  "",
  ...Object.entries(tokens.shadow).map(([k, v]) => `  --shadow-${k}: ${shadowCss(v)};`),
  "",
  `  --ease-standard: cubic-bezier(${tokens.motion.easing.standard.join(", ")});`,
  ...Object.entries(tokens.motion.duration).map(([k, v]) => `  --duration-${k}: ${v}ms;`),
];
const websiteOut = join(root, "../website/src/styles/tokens.css");
mkdirSync(dirname(websiteOut), { recursive: true });
writeFileSync(websiteOut, `${header}@theme {\n${tw.join("\n")}\n}\n`);

console.log(`✓ ${vars.length} tokens → dist/tokens.{css,json,js,d.ts} + website/src/styles/tokens.css`);
